let counter = 0;
const now = () => new Date().toISOString();
function doc<T extends Record<string, any>>(data: T): BaseDoc & T {
  counter += 1;
  return {
    id: `seed${counter.toString(36)}${Math.random().toString(36).slice(2, 8)}`,
    order: counter,
    createdAt: now(),
    updatedAt: now(),
    ...data,
  };
}
function list<T extends Record<string, any>>(items: T[]) {
  counter = 0;
  return items.map((i) => doc(i));
}

